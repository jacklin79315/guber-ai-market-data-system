"""Read-only native historical candles from Supabase for P3B replay.

Uses the existing collector.db client and never writes to the database.
No trading decisions are invented here: the caller supplies model decisions.
"""
from .raw_candle_adapter import raw_rows_to_candles
from .multi_model_replay import STRATEGY_TIMEFRAMES, replay_four_models

PAGE_SIZE = 1000

def load_native_candles(db, symbol, timeframe, *, start_ms=None, end_ms=None):
    """Fetch native candles in ascending order with keyset pagination."""
    if not symbol or timeframe not in STRATEGY_TIMEFRAMES.values():
        raise ValueError("invalid symbol or timeframe")
    rows = []
    cursor = start_ms
    first_page = True
    while True:
        params = {
            "select": "source,market,symbol,timeframe,open_time,close_time,open_price,high_price,low_price,close_price",
            "source": "eq.BINANCE",
            "market": "eq.SPOT",
            "symbol": "eq." + symbol,
            "timeframe": "eq." + timeframe,
            "order": "open_time.asc",
            "limit": str(PAGE_SIZE),
        }
        if cursor is not None:
            params["open_time"] = ("gte." if first_page else "gt.") + str(cursor)
        if end_ms is not None:
            params["close_time"] = "lte." + str(end_ms)
        batch = db("GET", "raw_candles", params)
        if not isinstance(batch, list):
            raise ValueError("raw_candles response must be a list")
        if not batch:
            break
        if rows and int(batch[0]["open_time"]) <= int(rows[-1]["open_time"]):
            raise ValueError("non-advancing raw candle page")
        rows.extend(batch)
        cursor = int(batch[-1]["open_time"])
        first_page = False
        if len(batch) < PAGE_SIZE:
            break
    if not rows:
        raise ValueError(f"no native candles for {symbol} {timeframe}")
    return raw_rows_to_candles(rows, symbol=symbol, timeframe=timeframe)

def replay_native_history(db, symbol, decisions_by_strategy, *,
                          start_ms=None, end_ms=None,
                          fee_rate=0.0, slippage_rate=0.0,
                          max_holding_ms_by_strategy=None):
    """Run four isolated accounts against original Supabase candle series.

    Decisions must be generated by the AI outside this module. Empty decisions
    are valid for pipeline verification but do not establish strategy returns.
    """
    candles = {tf: load_native_candles(db, symbol, tf, start_ms=start_ms,
                                      end_ms=end_ms)
               for tf in STRATEGY_TIMEFRAMES.values()}
    return replay_four_models(
        candles, decisions_by_strategy,
        fee_rate=fee_rate, slippage_rate=slippage_rate,
        max_holding_ms_by_strategy=max_holding_ms_by_strategy,
    )
